#!/usr/bin/env python3
"""v1.7 loop length in the GUI (track strips, Live view) and on Push 1, English -> German.
Writes src/plugin/Localisation_LoopLen.inc (UTF-8 as escapes, safe for every compiler).
    python3 tools/i18n/looplen_de.py
"""
import os

T = [
    # ---- host parameters, track SETUP
    ("Loop Length", "Loop-L\u00e4nge"), ("Loop Length Once", "Loop-L\u00e4nge einmalig"),
    ("Loop length", "Loop-L\u00e4nge"),
    # ---- loop length pill (track strips, Live view)
    ("AUTO", "AUTO"),
    ("Loop length - track %1", "Loop-L\u00e4nge \u2013 Spur %1"),
    ("Auto (ends with the next press)", "Auto (endet mit dem n\u00e4chsten Druck)"),
    # "1 bar" / "%1 bars" already exist (Localisation.cpp, Rhythm16)
    ("Applies to the next new recording (after CLEAR)", "Gilt f\u00fcr die n\u00e4chste neue Aufnahme (nach L\u00d6SCHEN)"),
    ("Loop length: the first recording ends by itself after this many bars (AUTO = ends with your next press). Click: choose, scroll / drag: change, right-click: MIDI learn",
     "Loop-L\u00e4nge: die erste Aufnahme endet nach so vielen Takten von selbst (AUTO = endet mit deinem n\u00e4chsten Druck). Klick: w\u00e4hlen, Scrollen / Ziehen: \u00e4ndern, Rechtsklick: MIDI-Learn"),
    ("Next recording only: %1 (set on the controller); the setting stays %2",
     "Nur die n\u00e4chste Aufnahme: %1 (am Controller gew\u00e4hlt); die Einstellung bleibt %2"),
    ("The track holds a loop: the length applies to the next new recording (after CLEAR)",
     "Die Spur enth\u00e4lt einen Loop: die L\u00e4nge gilt f\u00fcr die n\u00e4chste neue Aufnahme (nach L\u00d6SCHEN)"),
    # ---- Push 1 (FIXED LENGTH held)
    ("T%1 loop length: %2", "S%1 Loop-L\u00e4nge: %2"),
    ("T%1 Bars", "S%1 Takte"),
    ("LOOP LENGTH  pads: AUTO/1/2/4/8/16  encoder: step  alone: capture",
     "LOOP-L\u00c4NGE  Pads: AUTO/1/2/4/8/16  Encoder: \u00e4ndern  allein: Capture"),
]

def esc(s):
    out = ''
    for b in s.encode('utf-8'):
        if b < 0x80 and chr(b) not in '"\\':
            out += chr(b)
        elif chr(b) in '"\\':
            out += '\\' + chr(b)
        else:
            out += '\\x%02x" "' % b
    return out.replace('" ""', '"').replace('" "', '" "')

root = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
seen = set()
with open(os.path.join(root, 'src', 'plugin', 'Localisation_LoopLen.inc'), 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/i18n/looplen_de.py - v1.7 loop length in the GUI and on Push 1 (English -> German).\n')
    for en, de in T:
        if en in seen:
            continue
        seen.add(en)
        f.write('        { "%s", "%s" },\n' % (esc(en), esc(de)))
print(len(seen), 'entries')
