#!/usr/bin/env python3
"""Remote control (SETUP > Remote, livelooper control app), English -> German.
Writes src/plugin/Localisation_Remote.inc (UTF-8 as escapes, safe for every compiler).
    python3 tools/i18n/remote_de.py
"""
import os

T = [
    ("Remote", "Fernsteuerung"),
    ("Remote control (livelooper control app)", "Fernsteuerung (App livelooper control)"),
    ("Remote control is off", "Fernsteuerung ist aus"),
    ("Port %1 is in use (another livelooper?) - trying again", "Port %1 ist belegt (noch ein livelooper?) \u2013 neuer Versuch l\u00e4uft"),
    ("Ready: %1, port %2", "Bereit: %1, Port %2"),
    ("%1 connected", "%1 verbunden"),
    ("Port", "Port"),
    ("default", "Standard"),
    ("Pairing", "Koppeln"),
    ("Pairing code: %1", "Kopplungscode: %1"),
    ("New pairing code", "Neuer Kopplungscode"),
    ("Type this code in the app once; the device stays paired until you remove it",
     "Gib diesen Code einmal in der App ein; das Ger\u00e4t bleibt gekoppelt, bis du es entfernst"),
    ("Paired devices", "Gekoppelte Ger\u00e4te"),
    ("Remove %1", "%1 entfernen"),
    ("No paired devices", "Keine gekoppelten Ger\u00e4te"),
    ("Only devices in your local network can connect. Off by default.",
     "Nur Ger\u00e4te in deinem lokalen Netzwerk k\u00f6nnen sich verbinden. Standardm\u00e4\u00dfig aus."),
    ("REMOTE ON", "FERNSTEUERUNG AN"),
    ("REMOTE OFF", "FERNSTEUERUNG AUS"),
]

def esc(s):
    out = ''
    for b in s.encode('utf-8'):
        if b < 0x80 and chr(b) not in '"\\':
            out += chr(b)
        elif chr(b) in '"\\':
            out += '\\' + chr(b)
        else:
            out += '\\x%02x" "' % b
    return out.replace('" ""', '"').replace('" "', '" "')

root = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
seen = set()
with open(os.path.join(root, 'src', 'plugin', 'Localisation_Remote.inc'), 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/i18n/remote_de.py - remote control (English -> German).\n')
    for en, de in T:
        if en in seen:
            continue
        seen.add(en)
        f.write('        { "%s", "%s" },\n' % (esc(en), esc(de)))
